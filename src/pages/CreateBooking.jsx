import React, { useState } from "react";

// Use VITE_API_URL from your frontend .env file when available.
// Example: VITE_API_URL=https://api.speedexp.in/api
const API_BASE_URL = (
  import.meta.env.VITE_API_URL || "https://api.speedexp.in/api"
).replace(/\/+$/, "");

const STATUS_OPTIONS = [
  "Shipment Booked",
  "Material Received at Origin Office",
  "In Transit to Next Hub",
  "Vehicle Delayed",
  "Out For Delivery",
  "Delivered Successfully",
  "Shipment Cancelled",
  "Delivery Attempted - Customer Unavailable",
  "Vehicle Breakdown",
];

// Get the current date and time using the Asia/Kolkata time zone.
// Input values use the browser-friendly formats YYYY-MM-DD and HH:mm.
const getIndiaDateTime = () => {
  const parts = new Intl.DateTimeFormat("en-GB", {
    timeZone: "Asia/Kolkata",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).formatToParts(new Date());

  const values = Object.fromEntries(
    parts.map(({ type, value }) => [type, value])
  );

  return {
    bookingDate: `${values.year}-${values.month}-${values.day}`,
    bookingTime: `${values.hour}:${values.minute}`,
  };
};

// New forms start with the actual current India date and time.
// The admin can edit either field or clear both fields.
const createInitialForm = () => ({
  bookingType: "Offline",
  ...getIndiaDateTime(),

  trackingNumber: "",
  awdNumber: "",

  senderName: "",
  senderPhone: "",
  senderAddress: "",

  receiverName: "",
  receiverPhone: "",
  receiverAddress: "",

  packageType: "Parcel",
  weight: "",
  productCount: "1",

  invoiceNumber: "",
  eWayBillNumber: "",

  status: "Shipment Booked",
  currentLocation: "",
  remarks: "",
});

const inputStyle = {
  width: "100%",
  boxSizing: "border-box",
  padding: "11px 12px",
  border: "1px solid #cbd5e1",
  borderRadius: "7px",
  fontSize: "14px",
  backgroundColor: "#ffffff",
  color: "#0f172a",
};

const labelStyle = {
  display: "block",
  marginBottom: "6px",
  fontWeight: 600,
  fontSize: "13px",
  color: "#334155",
};

const fieldStyle = {
  minWidth: 0,
  marginBottom: "16px",
};

const sectionStyle = {
  padding: "20px",
  marginBottom: "20px",
  border: "1px solid #e2e8f0",
  borderRadius: "12px",
  backgroundColor: "#ffffff",
  boxShadow: "0 3px 12px rgba(15, 23, 42, 0.035)",
};

const gridStyle = {
  display: "grid",
  gridTemplateColumns: "repeat(auto-fit, minmax(min(100%, 220px), 1fr))",
  gap: "0 18px",
};

const buttonStyle = {
  padding: "12px 22px",
  border: "none",
  borderRadius: "8px",
  fontSize: "14px",
  fontWeight: 600,
  cursor: "pointer",
  transition: "opacity 0.2s ease, transform 0.2s ease",
};

function Field({
  label,
  name,
  value,
  onChange,
  type = "text",
  ...props
}) {
  return (
    <div style={fieldStyle}>
      <label htmlFor={name} style={labelStyle}>
        {label}
      </label>

      <input
        id={name}
        name={name}
        type={type}
        value={value}
        onChange={onChange}
        style={inputStyle}
        {...props}
      />
    </div>
  );
}

function SelectField({ label, name, value, onChange, children, ...props }) {
  return (
    <div style={fieldStyle}>
      <label htmlFor={name} style={labelStyle}>
        {label}
      </label>

      <select
        id={name}
        name={name}
        value={value}
        onChange={onChange}
        style={inputStyle}
        {...props}
      >
        {children}
      </select>
    </div>
  );
}

function Section({ title, children }) {
  return (
    <section style={sectionStyle}>
      <h2
        style={{
          margin: "0 0 20px",
          color: "#0b3d91",
          fontSize: "18px",
          fontWeight: 750,
        }}
      >
        {title}
      </h2>

      <div style={gridStyle}>{children}</div>
    </section>
  );
}

function Notice({ kind = "error", children }) {
  const isSuccess = kind === "success";

  return (
    <div
      role={isSuccess ? "status" : "alert"}
      style={{
        padding: "13px 16px",
        marginBottom: "20px",
        color: isSuccess ? "#166534" : "#991b1b",
        backgroundColor: isSuccess ? "#dcfce7" : "#fee2e2",
        border: `1px solid ${isSuccess ? "#bbf7d0" : "#fecaca"}`,
        borderRadius: "9px",
        lineHeight: 1.6,
      }}
    >
      {children}
    </div>
  );
}

export default function CreateBooking() {
  const [form, setForm] = useState(createInitialForm);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [success, setSuccess] = useState(null);

  // Update the form when any input changes.
  const handleChange = (event) => {
    const { name, value } = event.target;

    setForm((previousForm) => ({
      ...previousForm,
      [name]: value,
    }));

    setError("");
  };

  // Online tracking numbers are generated by this frontend.
  // Offline tracking numbers must be entered by the admin.
  const handleBookingTypeChange = (event) => {
    const bookingType = event.target.value;

    setForm((previousForm) => ({
      ...previousForm,
      bookingType,
      trackingNumber:
        bookingType === "Online" ? "" : previousForm.trackingNumber,
    }));

    setError("");
  };

  const generateTrackingNumber = () => {
    const number = Math.floor(100000 + Math.random() * 900000);
    return `SPEED${number}`;
  };

  // Validate all required fields before sending the request.
  const validateForm = () => {
    if (
      form.bookingType === "Offline" &&
      !form.trackingNumber.trim()
    ) {
      return "Please enter a tracking number for Offline booking.";
    }

    const requiredFields = [
      ["senderName", "sender name"],
      ["senderPhone", "sender phone"],
      ["senderAddress", "sender address"],
      ["receiverName", "receiver name"],
      ["receiverPhone", "receiver phone"],
      ["receiverAddress", "receiver address"],
    ];

    for (const [field, label] of requiredFields) {
      if (!form[field].trim()) {
        return `Please enter ${label}.`;
      }
    }

    if (
      form.weight !== "" &&
      (!Number.isFinite(Number(form.weight)) || Number(form.weight) < 0)
    ) {
      return "Weight must be a valid non-negative number.";
    }

    if (
      !Number.isInteger(Number(form.productCount)) ||
      Number(form.productCount) < 1
    ) {
      return "Product count must be a whole number of at least 1.";
    }

    if (
      form.bookingDate &&
      !/^\d{4}-\d{2}-\d{2}$/.test(form.bookingDate)
    ) {
      return "Please enter a valid booking date.";
    }

    if (
      form.bookingTime &&
      !/^([01]\d|2[0-3]):[0-5]\d$/.test(form.bookingTime)
    ) {
      return "Please enter a valid booking time.";
    }

    return "";
  };

  // Clear only the booking date/time fields.
  // The rest of the booking form remains unchanged.
  const handleClearBookingDateTime = () => {
    setForm((previousForm) => ({
      ...previousForm,
      bookingDate: "",
      bookingTime: "",
    }));

    setError("");
  };

  // Reset the whole form and restore the current India date/time.
  const handleReset = () => {
    setForm(createInitialForm());
    setError("");
    setSuccess(null);
  };

  // Create a shipment through POST /api/shipments.
  const handleSubmit = async (event) => {
    event.preventDefault();

    if (loading) return;

    setError("");
    setSuccess(null);

    const validationError = validateForm();

    if (validationError) {
      setError(validationError);
      return;
    }

    setLoading(true);

    try {
      const trackingNumber =
        form.bookingType === "Online"
          ? generateTrackingNumber()
          : form.trackingNumber.trim().toUpperCase();

      // Empty date/time values are intentionally sent as null.
      // The backend model/controller must save these fields.
      const payload = {
        bookingType: form.bookingType,
        trackingNumber,

        bookingDate: form.bookingDate || null,
        bookingTime: form.bookingTime || null,

        senderName: form.senderName.trim(),
        senderPhone: form.senderPhone.trim(),
        senderAddress: form.senderAddress.trim(),

        receiverName: form.receiverName.trim(),
        receiverPhone: form.receiverPhone.trim(),
        receiverAddress: form.receiverAddress.trim(),

        packageType: form.packageType,
        productCount: Number(form.productCount),

        invoiceNumber: form.invoiceNumber.trim(),
        eWayBillNumber: form.eWayBillNumber.trim(),

        status: form.status,
        currentLocation: form.currentLocation.trim(),
        remarks: form.remarks.trim(),
      };

      // AWD is optional. Do not send it when blank.
      if (form.awdNumber.trim()) {
        payload.awdNumber = form.awdNumber.trim().toUpperCase();
      }

      // Weight is optional. Do not send it when blank.
      if (form.weight !== "") {
        payload.weight = Number(form.weight);
      }

      const response = await fetch(`${API_BASE_URL}/shipments`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify(payload),
      });

      const responseData = await response.json().catch(() => ({}));

      if (!response.ok) {
        throw new Error(
          responseData.message ||
            responseData.error ||
            `Booking failed with HTTP ${response.status}.`
        );
      }

      const savedShipment =
        responseData.shipment ||
        responseData.data ||
        responseData.result ||
        responseData;

      setSuccess({
        trackingNumber: savedShipment.trackingNumber || trackingNumber,
        awdNumber: savedShipment.awdNumber || "",
        bookingType: form.bookingType,
        bookingDate: savedShipment.bookingDate ?? payload.bookingDate,
        bookingTime: savedShipment.bookingTime ?? payload.bookingTime,
      });

      // Reset after success. The next form gets a fresh India date/time.
      setForm(createInitialForm());
    } catch (submitError) {
      console.error("Create booking error:", submitError);

      setError(
        submitError.message ||
          "Unable to create booking. Please check your connection and try again."
      );
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="create-booking-page" style={{ minWidth: 0 }}>
      {/* Modern blue-gradient page header */}
      <header className="booking-page-header">
        <div className="booking-header-content">
          <nav className="booking-breadcrumb" aria-label="Breadcrumb">
            <span>Admin Dashboard</span>
            <span aria-hidden="true">/</span>
            <span aria-current="page">New Booking</span>
          </nav>

          <h1>Create Shipment Booking</h1>
          <p>
            Enter shipment information and save the booking. Manage sender,
            receiver, package, and delivery details in one place.
          </p>
        </div>

        <div
          className="booking-header-icon"
          aria-hidden="true"
          title="Create shipment"
        >
          📦
        </div>
      </header>

      {error && <Notice kind="error">{error}</Notice>}

      {success && (
        <Notice kind="success">
          <h3 style={{ margin: "0 0 10px", fontSize: "17px" }}>
            Booking created successfully!
          </h3>

          <p style={{ margin: "4px 0" }}>
            <strong>Tracking Number:</strong> {success.trackingNumber}
          </p>

          {success.awdNumber && (
            <p style={{ margin: "4px 0" }}>
              <strong>AWD Number:</strong> {success.awdNumber}
            </p>
          )}

          <p style={{ margin: "4px 0" }}>
            <strong>Booking Date:</strong>{" "}
            {success.bookingDate || "Not specified"}
          </p>

          <p style={{ margin: "4px 0" }}>
            <strong>Booking Time:</strong>{" "}
            {success.bookingTime || "Not specified"}
          </p>
        </Notice>
      )}

      <form onSubmit={handleSubmit}>
        <Section title="Booking Information">
          <SelectField
            label="Booking Type *"
            name="bookingType"
            value={form.bookingType}
            onChange={handleBookingTypeChange}
            required
          >
            <option value="Offline">Offline</option>
            <option value="Online">Online</option>
          </SelectField>

          <Field
            label="Tracking Number"
            name="trackingNumber"
            value={form.trackingNumber}
            onChange={handleChange}
            placeholder={
              form.bookingType === "Online"
                ? "Generated automatically"
                : "Enter tracking number"
            }
            required={form.bookingType === "Offline"}
            disabled={form.bookingType === "Online"}
          />

          <Field
            label="AWD Number (Optional)"
            name="awdNumber"
            value={form.awdNumber}
            onChange={handleChange}
            placeholder="Enter AWD number"
          />

          <Field
            label="Booking Date (Optional)"
            name="bookingDate"
            type="date"
            value={form.bookingDate}
            onChange={handleChange}
          />

          <Field
            label="Booking Time (Optional)"
            name="bookingTime"
            type="time"
            value={form.bookingTime}
            onChange={handleChange}
          />

          <div style={{ ...fieldStyle, alignSelf: "end" }}>
            <button
              type="button"
              onClick={handleClearBookingDateTime}
              style={{
                ...buttonStyle,
                color: "#0b3d91",
                backgroundColor: "#eaf4ff",
                border: "1px solid #bfdbfe",
              }}
            >
              Clear Date &amp; Time
            </button>
          </div>
        </Section>

        <Section title="Sender Information">
          <Field
            label="Sender Name *"
            name="senderName"
            value={form.senderName}
            onChange={handleChange}
            autoComplete="name"
            required
          />

          <Field
            label="Sender Phone *"
            name="senderPhone"
            value={form.senderPhone}
            onChange={handleChange}
            type="tel"
            autoComplete="tel"
            required
          />

          <Field
            label="Sender Address *"
            name="senderAddress"
            value={form.senderAddress}
            onChange={handleChange}
            autoComplete="street-address"
            required
          />
        </Section>

        <Section title="Receiver Information">
          <Field
            label="Receiver Name *"
            name="receiverName"
            value={form.receiverName}
            onChange={handleChange}
            required
          />

          <Field
            label="Receiver Phone *"
            name="receiverPhone"
            value={form.receiverPhone}
            onChange={handleChange}
            type="tel"
            required
          />

          <Field
            label="Receiver Address *"
            name="receiverAddress"
            value={form.receiverAddress}
            onChange={handleChange}
            required
          />
        </Section>

        <Section title="Package Information">
          <SelectField
            label="Package Type"
            name="packageType"
            value={form.packageType}
            onChange={handleChange}
          >
            <option value="Parcel">Parcel</option>
            <option value="Document">Document</option>
            <option value="Corporate Gifting">Corporate Gifting</option>
            <option value="Other">Other</option>
          </SelectField>

          <Field
            label="Weight (Optional)"
            name="weight"
            type="number"
            value={form.weight}
            onChange={handleChange}
            min="0"
            step="any"
            placeholder="Enter weight"
          />

          <Field
            label="Product Count *"
            name="productCount"
            type="number"
            value={form.productCount}
            onChange={handleChange}
            min="1"
            step="1"
            required
          />

          <Field
            label="Invoice Number (Optional)"
            name="invoiceNumber"
            value={form.invoiceNumber}
            onChange={handleChange}
          />

          <Field
            label="E-Way Bill Number (Optional)"
            name="eWayBillNumber"
            value={form.eWayBillNumber}
            onChange={handleChange}
          />
        </Section>

        <Section title="Shipment Status">
          <SelectField
            label="Initial Status *"
            name="status"
            value={form.status}
            onChange={handleChange}
            required
          >
            {STATUS_OPTIONS.map((status) => (
              <option key={status} value={status}>
                {status}
              </option>
            ))}
          </SelectField>

          <Field
            label="Current Location (Optional)"
            name="currentLocation"
            value={form.currentLocation}
            onChange={handleChange}
            placeholder="Enter current location"
          />

          <Field
            label="Remarks (Optional)"
            name="remarks"
            value={form.remarks}
            onChange={handleChange}
            placeholder="Add shipment remarks"
          />
        </Section>

        <div
          style={{
            display: "flex",
            flexWrap: "wrap",
            justifyContent: "flex-end",
            gap: "12px",
            marginBottom: "28px",
          }}
        >
          <button
            type="button"
            onClick={handleReset}
            disabled={loading}
            style={{
              ...buttonStyle,
              color: "#334155",
              backgroundColor: "#e2e8f0",
              opacity: loading ? 0.65 : 1,
            }}
          >
            Reset Form
          </button>

          <button
            type="submit"
            disabled={loading}
            style={{
              ...buttonStyle,
              color: "#ffffff",
              background: loading
                ? "#64748b"
                : "linear-gradient(115deg, #0b3d91, #00a7df)",
              boxShadow: "0 5px 14px rgba(11, 61, 145, 0.18)",
              opacity: loading ? 0.8 : 1,
              cursor: loading ? "not-allowed" : "pointer",
            }}
          >
            {loading ? "Creating Booking..." : "Create Booking"}
          </button>
        </div>
      </form>
    </div>
  );
}
